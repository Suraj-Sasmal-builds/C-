#include <iostream>
using namespace std;

int main()
{
    int a  = 26;
    int b = 20;

    // Decimal Value 

    cout<<"a : "<<dec<<a<<endl;
    cout<<"b : "<<dec<<b<<endl;

    // Hexadecimal value 
    cout<<"a : "<<hex<<a<<endl;
    cout<<"b : "<<hex<<b<<endl;
    
    // OCtal Value 
    cout<<"a : "<<oct<<a<<endl;
    cout<<"b : "<<oct<<b<<endl;

    return 0;

}